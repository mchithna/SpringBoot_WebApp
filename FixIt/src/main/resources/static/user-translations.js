let currentUserLang = localStorage.getItem('language') || 'en';

function updateUserLanguage(lang) {
    currentUserLang = lang;
    localStorage.setItem('language', lang);
    const skipTranslateIds = ['nav-user-name', 'welcome-header'];


    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        if (skipTranslateIds.includes(element.id)) {
            return; // Skip this element
        }
        const key = element.getAttribute('data-i18n');
        if (userTranslations[lang][key]) {
            // Check if element is an option in select
            if (element.tagName === 'OPTION') {
                element.textContent = userTranslations[lang][key];
            } else {
                element.textContent = userTranslations[lang][key];
            }
        }
    });
    
    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (userTranslations[lang][key]) {
            element.placeholder = userTranslations[lang][key];
        }
    });
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
}
