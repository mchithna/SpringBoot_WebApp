let currentProviderLang = localStorage.getItem('language') || 'en';

function updateProviderLanguage(lang) {
    currentProviderLang = lang;
    localStorage.setItem('language', lang);
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (providerTranslations[lang][key]) {
            element.textContent = providerTranslations[lang][key];
        }
    });
    
    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (providerTranslations[lang][key]) {
            element.placeholder = providerTranslations[lang][key];
        }
    });
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
}
