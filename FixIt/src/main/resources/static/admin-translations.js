let currentAdminLang = localStorage.getItem('language') || 'en';

function updateAdminLanguage(lang) {
    currentAdminLang = lang;
    localStorage.setItem('language', lang);
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (adminTranslations[lang][key]) {
            // Check if element is an option in select
            if (element.tagName === 'OPTION') {
                element.textContent = adminTranslations[lang][key];
            } else {
                element.textContent = adminTranslations[lang][key];
            }
        }
    });
    
    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (adminTranslations[lang][key]) {
            element.placeholder = adminTranslations[lang][key];
        }
    });
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
}
